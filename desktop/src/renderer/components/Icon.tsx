/** Hidden sprite. Mount once so every <Icon> can reference a symbol by name. */
export function IconSprite() {
  return (
    <svg
      id="oe-icon-sprite"
      xmlns="http://www.w3.org/2000/svg"
      aria-hidden="true"
      focusable="false"
    >
      {ICON_NAMES.map((name) => (
        <symbol
          key={name}
          id={`oe-icon-${name}`}
          viewBox="0 0 24 24"
          fill="none"
          stroke="currentColor"
          strokeWidth="2"
          strokeLinecap="round"
          strokeLinejoin="round"
        >
          {SYMBOLS[name]}
        </symbol>
      ))}
    </svg>
  );
}

export function Icon({ name, size = 16, className }: IconProps) {
  return (
    <svg
      className={['oe-icon', `oe-icon-${name}`, className].filter(Boolean).join(' ')}
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={2}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      focusable="false"
    >
      <use href={`#oe-icon-${name}`} />
    </svg>
  );
}
